-- Creates the database and tables for the Coding Club site.
-- HOW TO RUN (once per computer). Pick ONE:
--    MySQL Workbench: open this file (File > Open SQL Script) and click the
--      lightning-bolt "Execute" button.
-- 
-- It is SAFE TO RE-RUN: every statement uses IF NOT EXISTS, so existing tables
-- and their data are never touched. To start over with an empty database, run
--     DROP DATABASE coding_club;
-- and then run this file again.
--
-- ELLIOT'S DESIGN NOTES
--   * Three main entities: submissions, product_returns, billing.
--   * product_returns and billing each have a child table for their line items
--     (return_items, billing_items). One return/order has many items, so items
--     get their own table linked by a foreign key (a "one-to-many" relationship).
--   * ON DELETE CASCADE on the foreign keys means deleting a return or an order
--     automatically deletes its items too.
--   * Money uses DECIMAL(10,2), and not FLOAT, so cents are stored exactly.
--   * The table is named product_returns (not "returns") to stay clear of
--     MySQL reserved command words. The column is item_condition for the same reason
--     (CONDITION is a reserved word).
CREATE DATABASE IF NOT EXISTS coding_club
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;
USE coding_club;
-- ---------------------------------------------------------------------------
-- submissions: activity proposals from submission.html, reviewed on approval.html
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS submissions (
    -- A UUID generated by the server (36 characters), same as the old JSON version.
    id          CHAR(36)      NOT NULL,
    title       VARCHAR(100)  NOT NULL,
    speaker     VARCHAR(100)  NOT NULL,
    email       VARCHAR(254)  NOT NULL,
    -- ENUM limits the column to the listed values, like the dropdown on the form.
    category    ENUM('Python', 'HTML/CSS', 'JavaScript', 'SQL', 'Other') NOT NULL,
    abstract    TEXT          NOT NULL,
    status      ENUM('pending', 'approved', 'rejected') NOT NULL DEFAULT 'pending',
    created_at  DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- NULL until the row is edited; MySQL then refreshes it on every UPDATE.
    updated_at  DATETIME      NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
) ENGINE = InnoDB;

-- ---------------------------------------------------------------------------
-- product_returns: one row per return request from returns.html
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS product_returns (
    -- AUTO_INCREMENT: MySQL assigns 1, 2, 3... API however shows it as RET-1, RET-2 ... 
    id              INT UNSIGNED  NOT NULL AUTO_INCREMENT,
    customer_name   VARCHAR(100)  NOT NULL,
    email           VARCHAR(254)  NOT NULL,
    reason          VARCHAR(255)  NOT NULL,
    item_condition  VARCHAR(100)  NOT NULL,
    comments        TEXT          NULL,
    total           DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    created_at      DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      DATETIME      NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
) ENGINE = InnoDB;

-- return_items: the products inside one return (many rows per return)
CREATE TABLE IF NOT EXISTS return_items (
    id            INT UNSIGNED  NOT NULL AUTO_INCREMENT,
    return_id     INT UNSIGNED  NOT NULL,
    product_id    VARCHAR(50)   NOT NULL,
    product_name  VARCHAR(150)  NOT NULL,
    price         DECIMAL(10,2) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_return_items_return
        FOREIGN KEY (return_id) REFERENCES product_returns (id)
        ON DELETE CASCADE
) ENGINE = InnoDB;

-- ---------------------------------------------------------------------------
-- billing: one row per order from billing.html
-- The full card number and security code are NEVER stored: only the last 4
-- digits and the expiration date matching the old JSON behavior.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS billing (
    id               INT UNSIGNED  NOT NULL AUTO_INCREMENT,
    full_name        VARCHAR(100)  NOT NULL,
    address          VARCHAR(255)  NOT NULL,
    city             VARCHAR(100)  NOT NULL,
    state            VARCHAR(50)   NOT NULL,
    zip              VARCHAR(20)   NOT NULL,
    card_last4       CHAR(4)       NOT NULL,
    card_expiration  CHAR(5)       NOT NULL,
    shipping_method  VARCHAR(50)   NOT NULL DEFAULT 'Standard',
    total            DECIMAL(10,2) NOT NULL,
    created_at       DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       DATETIME      NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
) ENGINE = InnoDB;

-- billing_items: the products inside one order (many rows per order)
CREATE TABLE IF NOT EXISTS billing_items (
    id          INT UNSIGNED  NOT NULL AUTO_INCREMENT,
    billing_id  INT UNSIGNED  NOT NULL,
    product_id  VARCHAR(50)   NULL,
    title       VARCHAR(150)  NOT NULL,
    price       DECIMAL(10,2) NOT NULL,
    quantity    INT UNSIGNED  NOT NULL DEFAULT 1,
    PRIMARY KEY (id),
    CONSTRAINT fk_billing_items_billing
        FOREIGN KEY (billing_id) REFERENCES billing (id)
        ON DELETE CASCADE
) ENGINE = InnoDB;
